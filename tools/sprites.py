#!/usr/bin/env python3
"""Converts hand-authored pixel maps into LVGL 8 image arrays + PNG previews.

Pixel map format (assets/sprites/<name>.txt):
    line 1:  WxH frames=N
    then N blocks of H lines with W characters, blank lines between blocks.
    '.' = transparent, any other character = colour from assets/palette.txt
    (one "C #RRGGBB" per line, '#' lines starting with ';' are comments).

Usage:
    tools/sprites.py           regenerate src/assets/sprites.{c,h} and docs/sprites/*.png
    tools/sprites.py --check   exit 1 if the committed C/H files are out of date
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_DIR = os.path.join(ROOT, "assets", "sprites")
PALETTE_FILE = os.path.join(ROOT, "assets", "palette.txt")
OUT_C = os.path.join(ROOT, "firmware", "stargotchi", "src", "assets", "sprites.c")
OUT_H = os.path.join(ROOT, "firmware", "stargotchi", "src", "assets", "sprites.h")
PNG_DIR = os.path.join(ROOT, "docs", "sprites")


def parse_palette(text):
    pal = {}
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith(";"):
            continue
        ch, rgb = line.split()
        pal[ch] = int(rgb.lstrip("#"), 16)
    return pal


def rgb565(rgb):
    r, g, b = (rgb >> 16) & 0xFF, (rgb >> 8) & 0xFF, rgb & 0xFF
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def parse_sprite(name, text, palette):
    """Returns (frames, (w, h)); each frame is bytes in LV_IMG_CF_TRUE_COLOR_ALPHA."""
    lines = text.splitlines()
    m = re.match(r"(\d+)x(\d+)\s+frames=(\d+)", lines[0].strip())
    if not m:
        raise ValueError(f"{name}: line 1 must look like '32x32 frames=2'")
    w, h, n = (int(v) for v in m.groups())
    frames, rows, lineno = [], [], 1
    for raw in lines[1:]:
        lineno += 1
        row = raw.rstrip()
        if not row:
            continue
        if len(row) != w:
            raise ValueError(f"{name}: line {lineno} has {len(row)} pixels, expected {w}")
        out = bytearray()
        for ch in row:
            if ch == ".":
                out += b"\x00\x00\x00"
            elif ch in palette:
                c = rgb565(palette[ch])
                out += bytes([c & 0xFF, c >> 8, 0xFF])
            else:
                raise ValueError(f"{name}: line {lineno} uses unknown colour '{ch}'")
        rows.append(bytes(out))
        if len(rows) == h:
            frames.append(b"".join(rows))
            rows = []
    if rows or len(frames) != n:
        raise ValueError(f"{name}: expected {n} frames of {h} rows, got {len(frames)} (+{len(rows)} rows)")
    return frames, (w, h)


def load_all():
    with open(PALETTE_FILE) as f:
        palette = parse_palette(f.read())
    sprites = []
    for fn in sorted(os.listdir(SRC_DIR)):
        if not fn.endswith(".txt"):
            continue
        name = fn[:-4]
        with open(os.path.join(SRC_DIR, fn)) as f:
            frames, size = parse_sprite(fn, f.read(), palette)
        sprites.append((name, size, frames))
    return palette, sprites


def gen_c(sprites):
    out = ["/* Generated by tools/sprites.py - do not edit. */",
           "#include <lvgl.h>", '#include "sprites.h"', ""]
    for name, (w, h), frames in sprites:
        for i, data in enumerate(frames):
            sym = f"sg_img_{name}_{i}"
            out.append(f"static const uint8_t {sym}_map[] = {{")
            for k in range(0, len(data), 24):
                out.append("  " + ", ".join(f"0x{b:02x}" for b in data[k:k + 24]) + ",")
            out.append("};")
            out.append(f"const lv_img_dsc_t {sym} = {{")
            out.append(f"  .header.cf = LV_IMG_CF_TRUE_COLOR_ALPHA, .header.always_zero = 0,")
            out.append(f"  .header.reserved = 0, .header.w = {w}, .header.h = {h},")
            out.append(f"  .data_size = {len(data)}, .data = {sym}_map,")
            out.append("};")
            out.append("")
    return "\n".join(out)


def gen_h(sprites):
    out = ["/* Generated by tools/sprites.py - do not edit. */", "#pragma once",
           "#include <lvgl.h>", "", "#ifdef __cplusplus", 'extern "C" {', "#endif", ""]
    for name, _, frames in sprites:
        for i in range(len(frames)):
            out.append(f"extern const lv_img_dsc_t sg_img_{name}_{i};")
    out += ["", "#ifdef __cplusplus", "}", "#endif", ""]
    return "\n".join(out)


def write_pngs(palette, sprites, scale=8):
    from PIL import Image
    os.makedirs(PNG_DIR, exist_ok=True)
    for name, (w, h), frames in sprites:
        sheet = Image.new("RGB", ((w + 2) * len(frames) * scale, (h + 2) * scale), (0, 0, 0))
        for fi, data in enumerate(frames):
            img = Image.new("RGB", (w, h), (0, 0, 0))
            for y in range(h):
                for x in range(w):
                    o = (y * w + x) * 3
                    c = data[o] | (data[o + 1] << 8)
                    if data[o + 2]:
                        img.putpixel((x, y), (((c >> 11) & 31) * 255 // 31,
                                              ((c >> 5) & 63) * 255 // 63, (c & 31) * 255 // 31))
            sheet.paste(img.resize((w * scale, h * scale), Image.NEAREST),
                        ((fi * (w + 2) + 1) * scale, scale))
        sheet.save(os.path.join(PNG_DIR, f"{name}.png"))


def main(argv):
    palette, sprites = load_all()
    c, h = gen_c(sprites), gen_h(sprites)
    if "--check" in argv:
        ok = all(os.path.exists(p) and open(p).read() == t for p, t in ((OUT_C, c), (OUT_H, h)))
        if not ok:
            print("sprites.c/.h are out of date: run tools/sprites.py")
        return 0 if ok else 1
    os.makedirs(os.path.dirname(OUT_C), exist_ok=True)
    with open(OUT_C, "w") as f:
        f.write(c)
    with open(OUT_H, "w") as f:
        f.write(h)
    write_pngs(palette, sprites)
    print(f"{len(sprites)} sprites written")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
